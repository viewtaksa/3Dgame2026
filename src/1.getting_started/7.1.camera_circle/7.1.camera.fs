#version 330 core
out vec4 FragColor;

in vec2 TexCoord;
in vec3 FragPos;

uniform sampler2D texture1;
uniform sampler2D texture2;
uniform float time; // ????????????????????????

void main()
{
    vec4 texColor = mix(texture(texture1, TexCoord), texture(texture2, TexCoord), 0.2);
    
    // ???????? Multiple Lights ????????????????????????????????????
    float ambient = 0.3;
    float diffuse = max(0.0, sin(FragPos.x * 0.5 + time) * 0.5 + 0.5);
    
    FragColor = texColor * (ambient + diffuse);
}